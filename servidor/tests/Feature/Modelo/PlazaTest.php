<?php

namespace Tests\Feature\Modelo;

use App\Esquema\Regla;
use App\Esquema\Violacion;
use Illuminate\Database\QueryException;
use Illuminate\Support\Facades\DB;
use PHPUnit\Framework\Attributes\TestDox;
use Tests\Feature\Modelo\Soporte\EsquemaDePrueba;
use Tests\TestCase;

/**
 * La plaza en cada tabla de operación, no nula salvo en la lista de plaza opcional, y la llave compuesta con la plaza
 * en las tablas hijas, para que la base rechace una fila de otra plaza (NSV-2026-001-v8.pdf:4:Cláusula I;
 * ADR-0016, regla 4).
 *
 * Escenarios: modelo-E05 y modelo-E06 · Spec: openspec/changes/modelo-de-datos/specs/modelo-de-datos/spec.md
 */
class PlazaTest extends TestCase
{
    use EsquemaDePrueba;

    /** SQLSTATE de PostgreSQL cuando una llave foránea no encuentra su fila padre. */
    private const LLAVE_FORANEA_ROTA = '23503';

    private const REGLAS = [
        Regla::Plaza,
        Regla::PlazaNoNula,
        Regla::PlazaCompuesta,
    ];

    #[TestDox('modelo-E05 y modelo-E06: después de migrar, el esquema real cumple la regla de la plaza')]
    public function test_modelo_e05_y_e06_despues_de_migrar_el_esquema_real_cumple_la_regla_de_la_plaza(): void
    {
        $this->assertSame([], $this->violacionesDelEsquemaReal(self::REGLAS));
    }

    #[TestDox('modelo-E05: una tabla de operación sin plaza no pasa')]
    public function test_modelo_e05_una_tabla_de_operacion_sin_plaza_no_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table lavanderias (
                id_lavanderias bigint generated by default as identity primary key,
                nombre text not null,
                created_at timestamptz,
                updated_at timestamptz
            );
        SQL);

        $this->assertEquals([
            new Violacion(tabla: 'lavanderias', columna: null, regla: Regla::Plaza, esperado: 'id_plazas'),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('modelo-E05: una plaza vacía fuera de la lista de plaza opcional no pasa')]
    public function test_modelo_e05_una_plaza_vacia_fuera_de_la_lista_de_plaza_opcional_no_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table zonas (
                id_zonas bigint generated by default as identity primary key,
                id_plazas bigint references plazas (id_plazas) on delete restrict,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on zonas (id_plazas);
        SQL);

        $this->assertEquals([
            new Violacion(tabla: 'zonas', columna: 'id_plazas', regla: Regla::PlazaNoNula, esperado: 'id_plazas not null'),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('modelo-E05: las tablas de las listas del diseño pasan sin plaza o con la plaza vacía')]
    public function test_modelo_e05_las_tablas_de_las_listas_del_diseno_pasan_sin_plaza_o_con_la_plaza_vacia(): void
    {
        $this->crear(<<<'SQL'
            -- En la lista sin plaza: la persona no pertenece a una plaza.
            create table usuarios (
                id_usuarios bigint generated by default as identity primary key,
                created_at timestamptz,
                updated_at timestamptz
            );
            -- En la lista de plaza opcional: vacía si el punto no cae en ninguna zona.
            create table direcciones (
                id_direcciones bigint generated by default as identity primary key,
                id_plazas bigint references plazas (id_plazas) on delete restrict,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on direcciones (id_plazas);
        SQL);

        $this->assertSame([], array_map('strval', $this->violacionesDePrueba()));
    }

    #[TestDox('modelo-E06: la base rechaza un pedido de la plaza B con una lavandería de la plaza A')]
    public function test_modelo_e06_la_base_rechaza_un_pedido_de_la_plaza_b_con_una_lavanderia_de_la_plaza_a(): void
    {
        $this->crearLavanderiasYPedidos(<<<'SQL'
            constraint pedidos_id_lavanderias_id_plazas_foreign
                foreign key (id_lavanderias, id_plazas) references lavanderias (id_lavanderias, id_plazas)
                on delete restrict
        SQL);

        $plazaA = DB::table('plazas')->insertGetId(['nombre' => 'A'], 'id_plazas');
        $plazaB = DB::table('plazas')->insertGetId(['nombre' => 'B'], 'id_plazas');
        $lavanderia = DB::table('lavanderias')->insertGetId(
            ['id_plazas' => $plazaA, 'nombre' => 'Lavandería de la plaza A'],
            'id_lavanderias',
        );

        try {
            // Una transacción anidada es un savepoint: el error no aborta la transacción de la prueba.
            DB::transaction(fn () => DB::table('pedidos')->insert([
                'id_plazas' => $plazaB,
                'id_lavanderias' => $lavanderia,
                'folio' => 'B-1',
            ]));
            $this->fail('La base debió rechazar el pedido de otra plaza.');
        } catch (QueryException $error) {
            $this->assertSame(self::LLAVE_FORANEA_ROTA, $error->getCode());
            $this->assertStringContainsString('pedidos_id_lavanderias_id_plazas_foreign', $error->getMessage());
        }

        $this->assertSame(0, DB::table('pedidos')->count());

        // El mismo pedido, en la plaza de su lavandería, sí entra.
        DB::table('pedidos')->insert(['id_plazas' => $plazaA, 'id_lavanderias' => $lavanderia, 'folio' => 'A-1']);
        $this->assertSame(1, DB::table('pedidos')->count());

        // Y las tablas que lo impiden cumplen todas las reglas.
        $this->assertSame([], array_map('strval', $this->violacionesDePrueba()));
    }

    #[TestDox('modelo-E06: una llave foránea sin la plaza, hacia una tabla que la lleva, no pasa')]
    public function test_modelo_e06_una_llave_foranea_sin_la_plaza_hacia_una_tabla_que_la_lleva_no_pasa(): void
    {
        $this->crearLavanderiasYPedidos(<<<'SQL'
            constraint pedidos_id_lavanderias_foreign
                foreign key (id_lavanderias) references lavanderias (id_lavanderias) on delete restrict
        SQL);

        $this->assertEquals([
            new Violacion(
                tabla: 'pedidos',
                columna: 'id_lavanderias',
                regla: Regla::PlazaCompuesta,
                esperado: '(id_lavanderias, id_plazas)',
                llave: 'pedidos_id_lavanderias_foreign',
            ),
        ], $this->violacionesDePrueba());
    }

    /**
     * Plazas, lavanderías y pedidos, con la llave del pedido hacia su lavandería que se pasa.
     */
    private function crearLavanderiasYPedidos(string $llaveHaciaLaLavanderia): void
    {
        $this->crear(<<<SQL
            create table plazas (
                id_plazas bigint generated by default as identity primary key,
                nombre text not null unique,
                created_at timestamptz,
                updated_at timestamptz
            );
            create table lavanderias (
                id_lavanderias bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                nombre text not null,
                created_at timestamptz,
                updated_at timestamptz,
                unique (id_lavanderias, id_plazas)
            );
            create index on lavanderias (id_plazas);
            create table pedidos (
                id_pedidos bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                id_lavanderias bigint not null,
                folio text not null,
                created_at timestamptz,
                updated_at timestamptz,
                {$llaveHaciaLaLavanderia}
            );
            create index on pedidos (id_plazas);
            create index on pedidos (id_lavanderias, id_plazas);
        SQL);
    }
}
