/**
 * Los tipos por nombre de columna, la fecha de alta y de cambio, las llaves foráneas con índice y ON DELETE RESTRICT,
 * ninguna columna de tarjeta y ningún nombre de proveedor de pagos (NSV-2026-001-v8.pdf:20:ANEXO A, Sección A.3;
 * ADR-0016, reglas 6, 7 y 10; design.md, decisión 3).
 *
 * Escenarios: modelo-E07, modelo-E08, modelo-E09, modelo-E10, modelo-E13, modelo-E14 y modelo-E17 ·
 * Spec: openspec/changes/modelo-de-datos/specs/modelo-de-datos/spec.md
 */
class TiposEIntegridadTest extends TestCase
{
    use EsquemaDePrueba;

    private const REGLAS = [
        Regla::Dinero,
        Regla::Porcentaje,
        Regla::Cantidad,
        Regla::Instante,
        Regla::HoraDelDia,
        Regla::SinFlotantes,
        Regla::Mapa,
        Regla::FechasDeAltaYCambio,
        Regla::ForaneaRestrict,
        Regla::ForaneaConIndice,
        Regla::DatosDeTarjeta,
        Regla::ProveedorDePagos,
    ];

    private const SIN_DATOS_DE_TARJETA = 'solo la referencia de la pasarela, la marca y los últimos 4 dígitos';

    private const SIN_PROVEEDOR = 'un nombre sin el proveedor: pasarela o id_pasarela_<cosa>';

    #[TestDox('modelo-E07 a modelo-E17: después de migrar, el esquema real cumple los tipos y la integridad')]
    public function test_modelo_e07_a_e17_despues_de_migrar_el_esquema_real_cumple_los_tipos_y_la_integridad(): void
    {
        $this->assertSame([], $this->violacionesDelEsquemaReal(self::REGLAS));
    }

    #[TestDox('modelo-E07 a modelo-E17: las tablas con los tipos y las llaves del modelo pasan')]
    public function test_modelo_e07_a_e17_las_tablas_con_los_tipos_y_las_llaves_del_modelo_pasan(): void
    {
        $this->crear(<<<'SQL'
            create table usuarios (
                id_usuarios bigint generated by default as identity primary key,
                created_at timestamptz,
                updated_at timestamptz,
                deleted_at timestamptz
            );
            create table pedidos (
                id_pedidos bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                id_usuarios bigint not null references usuarios (id_usuarios) on delete restrict,
                monto_estimado numeric(12,2),
                precio_unitario numeric(12,2),
                envio numeric(12,2),
                comision_porcentaje numeric(5,2),
                cantidad_estimada numeric(8,2),
                ventana_inicio timestamp(0) with time zone,
                vigente_desde timestamptz,
                confirmado_en timestamptz,
                hora_inicio time,
                ubicacion geography(Point, 4326),
                pasarela text,
                id_pasarela_orden text,
                marca text,
                ultimos_4 char(4),
                created_at timestamp(0) with time zone,
                updated_at timestamp(0) with time zone
            );
            create index on pedidos (id_plazas);
            -- Un índice compuesto que empieza con la columna de la llave también la cubre.
            create index on pedidos (id_usuarios, created_at);
            -- Una tabla de enlace no lleva created_at ni updated_at.
            create table rol_usuario (
                id_usuarios bigint not null references usuarios (id_usuarios) on delete restrict,
                id_roles bigint not null,
                primary key (id_usuarios, id_roles)
            );
        SQL);

        $this->assertSame([], array_map('strval', $this->violacionesDePrueba()));
    }

    #[TestDox('modelo-E07: un monto con decimales flotantes no pasa')]
    public function test_modelo_e07_un_monto_con_decimales_flotantes_no_pasa(): void
    {
        $this->crearTabla('pagos', 'monto double precision not null');

        $this->assertEquals([
            new Violacion(tabla: 'pagos', columna: 'monto', regla: Regla::Dinero, esperado: 'numeric(12,2)'),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('modelo-E07: un precio, un porcentaje o una cantidad con otra precisión no pasan')]
    public function test_modelo_e07_un_precio_un_porcentaje_o_una_cantidad_con_otra_precision_no_pasan(): void
    {
        $this->crearTabla('pedido_servicios', <<<'SQL'
            precio_unitario numeric(10,2),
            comision_porcentaje numeric(12,2),
            cantidad_real integer
        SQL);

        $this->assertEquals([
            new Violacion(
                tabla: 'pedido_servicios',
                columna: 'precio_unitario',
                regla: Regla::Dinero,
                esperado: 'numeric(12,2)',
            ),
            new Violacion(
                tabla: 'pedido_servicios',
                columna: 'comision_porcentaje',
                regla: Regla::Porcentaje,
                esperado: 'numeric(5,2)',
            ),
            new Violacion(
                tabla: 'pedido_servicios',
                columna: 'cantidad_real',
                regla: Regla::Cantidad,
                esperado: 'numeric(8,2)',
            ),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('modelo-E07: una columna que no es dinero tampoco puede ser real ni double precision')]
