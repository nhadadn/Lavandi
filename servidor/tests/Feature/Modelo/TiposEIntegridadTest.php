    #[TestDox('modelo-E17: una fecha de alta o de cambio sin zona horaria no pasa')]
    public function test_modelo_e17_una_fecha_de_alta_o_de_cambio_sin_zona_horaria_no_pasa(): void
    {
        // Es lo que deja $table->timestamps() de Laravel; las migraciones usan timestampsTz().
        $this->crear(<<<'SQL'
            create table calificaciones (
                id_calificaciones bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                created_at timestamp(0) without time zone,
                updated_at timestamp(0) without time zone
            );
            create index on calificaciones (id_plazas);
        SQL);

        $this->assertEquals([
            new Violacion(
                tabla: 'calificaciones',
                columna: 'created_at',
                regla: Regla::FechasDeAltaYCambio,
                esperado: 'timestamptz',
            ),
            new Violacion(
                tabla: 'calificaciones',
                columna: 'updated_at',
                regla: Regla::FechasDeAltaYCambio,
                esperado: 'timestamptz',
            ),
        ], $this->violacionesDePrueba());
    }

    /**
     * Una tabla de operación que cumple las demás reglas, con las columnas que se pasan.
     */
    private function crearTabla(string $tabla, string $columnas): void
    {
        $this->crear(<<<SQL
            create table {$tabla} (
                id_{$tabla} bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                {$columnas},
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on {$tabla} (id_plazas);
        SQL);
    }

    /**
     * Usuarios y sus direcciones, con la llave de la dirección hacia el usuario declarada con lo que se pasa y, si se
     * pide, su índice.
     */
    private function crearUsuariosYDirecciones(string $alBorrar, ?string $indice = '(id_usuarios)'): void
    {
        $this->crear(<<<SQL
            create table usuarios (
                id_usuarios bigint generated by default as identity primary key,
                created_at timestamptz,
                updated_at timestamptz
            );
            create table direcciones (
                id_direcciones bigint generated by default as identity primary key,
                id_plazas bigint references plazas (id_plazas) on delete restrict,
                id_usuarios bigint not null,
                created_at timestamptz,
                updated_at timestamptz,
                constraint direcciones_id_usuarios_foreign
                    foreign key (id_usuarios) references usuarios (id_usuarios) {$alBorrar}
            );
            create index on direcciones (id_plazas);
        SQL);

        if ($indice !== null) {
            $this->crear("create index on direcciones {$indice}");
        }
    }
