    #[TestDox('modelo-E14: una tabla o una columna con el nombre del proveedor de pagos no pasa')]
    public function test_modelo_e14_una_tabla_o_una_columna_con_el_nombre_del_proveedor_de_pagos_no_pasa(): void
    {
        $this->crearTabla('eventos_stripe', 'tipo text');
        $this->crearTabla('pagos', 'conekta_orden_id text, id_pasarela_orden text, pasarela text');

        $this->assertEquals([
            new Violacion(tabla: 'eventos_stripe', columna: null, regla: Regla::ProveedorDePagos, esperado: self::SIN_PROVEEDOR),
            // La llave primaria, id_<tabla>, hereda el nombre del proveedor.
            new Violacion(
                tabla: 'eventos_stripe',
                columna: 'id_eventos_stripe',
                regla: Regla::ProveedorDePagos,
                esperado: self::SIN_PROVEEDOR,
            ),
            new Violacion(
                tabla: 'pagos',
                columna: 'conekta_orden_id',
                regla: Regla::Identificador,
                esperado: 'un nombre que empiece con id_ y no termine en _id',
            ),
            new Violacion(
                tabla: 'pagos',
                columna: 'conekta_orden_id',
                regla: Regla::ProveedorDePagos,
                esperado: self::SIN_PROVEEDOR,
            ),
        ], $this->violacionesDePrueba());
    }

