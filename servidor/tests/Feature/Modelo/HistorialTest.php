<?php

namespace Tests\Feature\Modelo;

use Illuminate\Database\QueryException;
use Illuminate\Support\Facades\DB;
use PHPUnit\Framework\Attributes\TestDox;
use Tests\Feature\Modelo\Soporte\EsquemaDePrueba;
use Tests\TestCase;

/**
 * El historial no se borra: la función impedir_cambio(), con sus triggers BEFORE DELETE y BEFORE UPDATE, hace que la
 * base rechace la operación aunque el código no la haya validado (NSV-2026-001-v8.pdf:20:ANEXO A, Sección A.3,
 * "historial completo"; ADR-0016, regla 6; design.md, decisión 4).
 *
 * Los triggers de pedidos, pedido_eventos, pagos y reembolsos nacen con su tabla, en su cambio. Aquí se prueban sobre
 * tablas de prueba con los mismos triggers.
 *
 * Escenarios: modelo-E11 y modelo-E12 · Spec: openspec/changes/modelo-de-datos/specs/modelo-de-datos/spec.md
 */
class HistorialTest extends TestCase
{
    use EsquemaDePrueba;

    /** SQLSTATE restrict_violation: el que lanza impedir_cambio(). */
    private const CAMBIO_IMPEDIDO = '23001';

    #[TestDox('modelo-E11: la base rechaza borrar un pedido')]
    public function test_modelo_e11_la_base_rechaza_borrar_un_pedido(): void
    {
        $this->crearPedidos();
        $pedido = DB::table('pedidos')->insertGetId(['folio' => 'A-1'], 'id_pedidos');

        $this->assertCambioImpedido(
            fn () => DB::delete('delete from pedidos where id_pedidos = ?', [$pedido]),
            'DELETE',
            'pedidos',
        );

        $this->assertSame('A-1', DB::table('pedidos')->where('id_pedidos', $pedido)->value('folio'));
    }

    #[TestDox('modelo-E11: TRUNCATE no dispara el trigger, así que las pruebas pueden vaciar la base')]
    public function test_modelo_e11_truncate_no_dispara_el_trigger_asi_que_las_pruebas_pueden_vaciar_la_base(): void
    {
        $this->crearPedidos();
        DB::table('pedidos')->insert(['folio' => 'A-1']);

        DB::statement('truncate table pedidos');

        $this->assertSame(0, DB::table('pedidos')->count());
    }

    #[TestDox('modelo-E12: la base rechaza editar el estado o la fecha de un evento del pedido')]
    public function test_modelo_e12_la_base_rechaza_editar_el_estado_o_la_fecha_de_un_evento_del_pedido(): void
    {
        $this->crearEventos();
        $evento = DB::table('pedido_eventos')->insertGetId(
            ['id_estados_pedido' => 1, 'ocurrido_en' => '2026-11-20 10:00:00+00'],
            'id_pedido_eventos',
        );

        $this->assertCambioImpedido(
            fn () => DB::update('update pedido_eventos set id_estados_pedido = 2 where id_pedido_eventos = ?', [$evento]),
            'UPDATE',
            'pedido_eventos',
        );
        $this->assertCambioImpedido(
            fn () => DB::update(
                "update pedido_eventos set ocurrido_en = '2026-11-21 10:00:00+00' where id_pedido_eventos = ?",
                [$evento],
            ),
            'UPDATE',
            'pedido_eventos',
        );

        // El evento sigue como se guardó. Se compara el instante, no su texto, que depende de la zona de la sesión.
        $this->assertTrue((bool) DB::scalar(
            "select id_estados_pedido = 1 and ocurrido_en = '2026-11-20 10:00:00+00'::timestamptz
               from pedido_eventos where id_pedido_eventos = ?",
            [$evento],
        ));
    }

    #[TestDox('modelo-E12: un evento del pedido no se borra, y el siguiente se agrega como fila nueva')]
    public function test_modelo_e12_un_evento_del_pedido_no_se_borra_y_el_siguiente_se_agrega_como_fila_nueva(): void
    {
        $this->crearEventos();
        $evento = DB::table('pedido_eventos')->insertGetId(
            ['id_estados_pedido' => 1, 'ocurrido_en' => '2026-11-20 10:00:00+00'],
            'id_pedido_eventos',
        );

        $this->assertCambioImpedido(
            fn () => DB::delete('delete from pedido_eventos where id_pedido_eventos = ?', [$evento]),
            'DELETE',
            'pedido_eventos',
        );

        // Solo se agrega: el cambio de estado es otra fila.
        DB::table('pedido_eventos')->insert(['id_estados_pedido' => 2, 'ocurrido_en' => '2026-11-20 11:00:00+00']);
        $this->assertSame([1, 2], DB::table('pedido_eventos')->orderBy('ocurrido_en')->pluck('id_estados_pedido')->all());
    }

    /**
     * Un pedido de prueba con el trigger que llevará pedidos: no se borra.
     */
    private function crearPedidos(): void
    {
        $this->crear(<<<'SQL'
            create table pedidos (
                id_pedidos bigint generated by default as identity primary key,
                folio text not null
            );
            create trigger pedidos_impedir_borrado
                before delete on pedidos for each row execute function impedir_cambio();
        SQL);
    }

    /**
     * Eventos de prueba con los triggers que llevará pedido_eventos: no se borran ni se editan.
     */
    private function crearEventos(): void
    {
        $this->crear(<<<'SQL'
            create table pedido_eventos (
                id_pedido_eventos bigint generated by default as identity primary key,
                id_estados_pedido bigint not null,
                ocurrido_en timestamptz not null
            );
            create trigger pedido_eventos_impedir_borrado
                before delete on pedido_eventos for each row execute function impedir_cambio();
            create trigger pedido_eventos_impedir_edicion
                before update on pedido_eventos for each row execute function impedir_cambio();
        SQL);
    }

    /**
     * La operación falla con el error de impedir_cambio(), que nombra la operación y la tabla. Corre en una
     * transacción anidada, un savepoint, para que el error no aborte la transacción de la prueba.
     */
    private function assertCambioImpedido(callable $operacion, string $sentencia, string $tabla): void
    {
        try {
            DB::transaction($operacion);
            $this->fail("La base debió rechazar {$sentencia} sobre {$tabla}.");
        } catch (QueryException $error) {
            $this->assertSame(self::CAMBIO_IMPEDIDO, $error->getCode(), $error->getMessage());
            $this->assertStringContainsString("impedir_cambio: {$sentencia} sobre {$tabla}", $error->getMessage());
        }
    }
}
