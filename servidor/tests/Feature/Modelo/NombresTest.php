<?php

namespace Tests\Feature\Modelo;

use App\Esquema\Regla;
use App\Esquema\Violacion;
use PHPUnit\Framework\Attributes\TestDox;
use Tests\Feature\Modelo\Soporte\EsquemaDePrueba;
use Tests\TestCase;

/**
 * Los nombres de tablas, llaves y columnas: todo identificador empieza con id_, la llave primaria es id_<tabla>, la
 * foránea lleva el nombre de la llave a la que apunta y todo va en minúsculas (ADR-0016, regla 5; C-190 y C-194).
 *
 * Escenarios: modelo-E01 a modelo-E04 · Spec: openspec/changes/modelo-de-datos/specs/modelo-de-datos/spec.md
 */
class NombresTest extends TestCase
{
    use EsquemaDePrueba;

    private const REGLAS = [
        Regla::Minusculas,
        Regla::LlavePrimaria,
        Regla::Identificador,
        Regla::NombreDeForanea,
    ];

    #[TestDox('modelo-E01 a modelo-E04: después de migrar, el esquema real cumple las reglas de nombres')]
    public function test_modelo_e01_a_e04_despues_de_migrar_el_esquema_real_cumple_las_reglas_de_nombres(): void
    {
        $this->assertSame([], $this->violacionesDelEsquemaReal(self::REGLAS));
    }

    #[TestDox('modelo-E01 a modelo-E04: las tablas con los nombres del modelo pasan')]
    public function test_modelo_e01_a_e04_las_tablas_con_los_nombres_del_modelo_pasan(): void
    {
        $this->crear(<<<'SQL'
            create table usuarios (
                id_usuarios bigint generated by default as identity primary key,
                id_publico char(26) not null unique,
                created_at timestamptz,
                updated_at timestamptz
            );
            create table pagos (
                id_pagos bigint generated by default as identity primary key,
                id_publico char(26) not null unique,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                id_usuarios bigint not null references usuarios (id_usuarios) on delete restrict,
                id_pasarela_orden text,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on pagos (id_plazas);
            create index on pagos (id_usuarios);
            -- Una tabla de enlace no lleva id_<tabla>: su llave es la pareja.
            create table rol_usuario (
                id_usuarios bigint not null references usuarios (id_usuarios) on delete restrict,
                id_roles bigint not null,
                primary key (id_usuarios, id_roles)
            );
            -- Una tabla del framework conserva sus nombres y queda fuera de toda regla.
            create table sessions (id varchar primary key, user_id bigint);
        SQL);

        $this->assertSame([], array_map('strval', $this->violacionesDePrueba()));
    }

    #[TestDox('modelo-E01: una llave primaria con otro nombre no pasa')]
    public function test_modelo_e01_una_llave_primaria_con_otro_nombre_no_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table zonas (
                id bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                nombre text not null,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on zonas (id_plazas);
        SQL);

        $this->assertEquals([
            new Violacion(tabla: 'zonas', columna: 'id', regla: Regla::LlavePrimaria, esperado: 'id_zonas'),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('modelo-E01: una tabla sin llave primaria no pasa')]
    public function test_modelo_e01_una_tabla_sin_llave_primaria_no_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table zonas (
                id_zonas bigint not null,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on zonas (id_plazas);
        SQL);

        $this->assertEquals([
            new Violacion(tabla: 'zonas', columna: null, regla: Regla::LlavePrimaria, esperado: 'id_zonas'),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('modelo-E02: una columna que termina en _id no pasa')]
    public function test_modelo_e02_una_columna_que_termina_en_id_no_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table evidencias (
                id_evidencias bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                pedido_id bigint not null,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on evidencias (id_plazas);
        SQL);

        $this->assertEquals([
            new Violacion(
                tabla: 'evidencias',
                columna: 'pedido_id',
                regla: Regla::Identificador,
                esperado: 'un nombre que empiece con id_ y no termine en _id',
            ),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('modelo-E03: una llave foránea con otro nombre no pasa')]
    public function test_modelo_e03_una_llave_foranea_con_otro_nombre_no_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table usuarios (
                id_usuarios bigint generated by default as identity primary key,
                created_at timestamptz,
                updated_at timestamptz
            );
            create table pedidos (
                id_pedidos bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                id_cliente bigint not null
                    constraint pedidos_id_cliente_foreign references usuarios (id_usuarios) on delete restrict,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on pedidos (id_plazas);
            create index on pedidos (id_cliente);
        SQL);

        $this->assertEquals([
            new Violacion(
                tabla: 'pedidos',
                columna: 'id_cliente',
                regla: Regla::NombreDeForanea,
                esperado: 'id_usuarios',
                llave: 'pedidos_id_cliente_foreign',
            ),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('modelo-E04: un nombre de columna con mayúsculas no pasa')]
    public function test_modelo_e04_un_nombre_de_columna_con_mayusculas_no_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table pedido_servicios (
                id_pedido_servicios bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                "Id_Pedidos" bigint not null,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on pedido_servicios (id_plazas);
        SQL);

        $this->assertEquals([
            new Violacion(
                tabla: 'pedido_servicios',
                columna: 'Id_Pedidos',
                regla: Regla::Minusculas,
                esperado: 'id_pedidos',
            ),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('modelo-E04: un nombre de tabla con mayúsculas no pasa')]
    public function test_modelo_e04_un_nombre_de_tabla_con_mayusculas_no_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table "Zonas" (
                id_zonas bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on "Zonas" (id_plazas);
        SQL);

        $this->assertEquals([
            new Violacion(tabla: 'Zonas', columna: null, regla: Regla::Minusculas, esperado: 'zonas'),
        ], $this->violacionesDePrueba());
    }
}
