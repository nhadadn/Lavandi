<?php

namespace Tests\Feature\Plazas;

use App\Esquema\Regla;
use App\Esquema\Violacion;
use PHPUnit\Framework\Attributes\TestDox;
use Tests\Feature\Modelo\Soporte\EsquemaDePrueba;
use Tests\TestCase;

/**
 * Toda fila de operación lleva su plaza: en cada tabla que no está en la lista de tablas sin plaza, id_plazas existe,
 * es no nula salvo en las cuatro de plaza opcional y tiene llave foránea a plazas (NSV-2026-001-v8.pdf:4:Cláusula I;
 * ADR-0004 y ADR-0016; vault/arquitectura/modelo-multi-plaza.md).
 *
 * La lista es una sola, la de modelo-de-datos en config/modelo.php (openspec/changes/plazas-y-zonas/design.md,
 * decisión 5), y la prueba es la misma prueba de esquema, App\Esquema\RevisorDeEsquema: modelo-E05 pide la columna y
 * que sea no nula; plazas-E09 agrega la llave foránea a plazas.
 *
 * Escenario: plazas-E09 · Spec: openspec/changes/plazas-y-zonas/specs/plazas/spec.md
 */
class FilaDeOperacionConPlazaTest extends TestCase
{
    use EsquemaDePrueba;

    private const REGLAS = [
        Regla::Plaza,
        Regla::PlazaNoNula,
        Regla::PlazaForanea,
    ];

    #[TestDox('plazas-E09: después de migrar, toda tabla fuera de la lista lleva id_plazas con llave a plazas')]
    public function test_plazas_e09_despues_de_migrar_toda_tabla_fuera_de_la_lista_lleva_id_plazas_con_llave_a_plazas(): void
    {
        $this->assertSame([], $this->violacionesDelEsquemaReal(self::REGLAS));

        // Las tablas de operación de este cambio no están en ninguna lista: la prueba las revisa.
        foreach (['zonas', 'parametros_plaza'] as $tabla) {
            $this->assertNotContains($tabla, config('modelo.sin_plaza'));
            $this->assertNotContains($tabla, config('modelo.plaza_opcional'));
            $this->assertNotContains($tabla, config('modelo.del_framework'));
        }
    }

    #[TestDox('plazas-E09: la lista de tablas sin plaza es la de modelo-de-datos, y la de plaza opcional tiene cinco')]
    public function test_plazas_e09_la_lista_de_tablas_sin_plaza_es_la_de_modelo_de_datos_y_la_de_plaza_opcional_tiene_cinco(): void
    {
        // Las del escenario: los catálogos, plazas, las de cuentas y las de la pasarela. Los tres del territorio los
        // agregó la dirección asistida (openspec/changes/direcciones/design.md, tarea 4.1; C-238), y testimonios y
        // logos_prensa, la landing (openspec/changes/landing/design.md, tareas 4.0 y 4.0b).
        $this->assertEqualsCanonicalizing([
            'roles',
            'tipos_servicio',
            'unidades_medida',
            'estados_pedido',
            'entidades_federativas',
            'municipios',
            'colonias',
            'plazas',
            'usuarios',
            'rol_usuario',
            'cuentas_externas',
            'dispositivos',
            'actividad_usuarios',
            'eventos_pasarela',
            'metodos_pago_guardados',
            'movimientos_pasarela',
            'testimonios',
            'logos_prensa',
        ], config('modelo.sin_plaza'));

        // comisiones entró con la comisión global, una para todas las plazas (administracion, Open Questions 4).
        $this->assertEqualsCanonicalizing(
            ['avisos_masivos', 'comisiones', 'reportes_soporte', 'repartidores', 'direcciones'],
            config('modelo.plaza_opcional'),
        );
    }

    #[TestDox('plazas-E09: una tabla de operación con id_plazas no nula y llave a plazas pasa')]
    public function test_plazas_e09_una_tabla_de_operacion_con_id_plazas_no_nula_y_llave_a_plazas_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table plazas (
                id_plazas bigint generated by default as identity primary key,
                created_at timestamptz,
                updated_at timestamptz
            );
            create table lavanderias (
                id_lavanderias bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on lavanderias (id_plazas);
            -- De plaza opcional: vacía, pero con su llave a plazas.
            create table direcciones (
                id_direcciones bigint generated by default as identity primary key,
                id_plazas bigint references plazas (id_plazas) on delete restrict,
                created_at timestamptz,
                updated_at timestamptz
            );
            create index on direcciones (id_plazas);
            -- Sin plaza, en la lista.
            create table usuarios (
                id_usuarios bigint generated by default as identity primary key,
                created_at timestamptz,
                updated_at timestamptz
            );
        SQL);

        $this->assertSame([], array_map('strval', $this->violacionesDePrueba()));
    }

    #[TestDox('plazas-E09: una tabla de operación con id_plazas sin llave a plazas no pasa')]
    public function test_plazas_e09_una_tabla_de_operacion_con_id_plazas_sin_llave_a_plazas_no_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table lavanderias (
                id_lavanderias bigint generated by default as identity primary key,
                id_plazas bigint not null,
                created_at timestamptz,
                updated_at timestamptz
            );
        SQL);

        $this->assertEquals([
            new Violacion(
                tabla: 'lavanderias',
                columna: 'id_plazas',
                regla: Regla::PlazaForanea,
                esperado: 'llave foránea a plazas (id_plazas)',
            ),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('plazas-E09: la llave compuesta hacia la tabla padre no sustituye la llave a plazas')]
    public function test_plazas_e09_la_llave_compuesta_hacia_la_tabla_padre_no_sustituye_la_llave_a_plazas(): void
    {
        $this->crear(<<<'SQL'
            create table plazas (
                id_plazas bigint generated by default as identity primary key,
                created_at timestamptz,
                updated_at timestamptz
            );
            create table lavanderias (
                id_lavanderias bigint generated by default as identity primary key,
                id_plazas bigint not null references plazas (id_plazas) on delete restrict,
                created_at timestamptz,
                updated_at timestamptz,
                unique (id_lavanderias, id_plazas)
            );
            create index on lavanderias (id_plazas);
            -- La hija lleva solo la llave compuesta con la plaza hacia su lavandería.
            create table lavanderia_fotos (
                id_lavanderia_fotos bigint generated by default as identity primary key,
                id_lavanderias bigint not null,
                id_plazas bigint not null,
                created_at timestamptz,
                updated_at timestamptz,
                foreign key (id_lavanderias, id_plazas) references lavanderias (id_lavanderias, id_plazas)
                    on delete restrict
            );
            create index on lavanderia_fotos (id_lavanderias, id_plazas);
        SQL);

        $this->assertEquals([
            new Violacion(
                tabla: 'lavanderia_fotos',
                columna: 'id_plazas',
                regla: Regla::PlazaForanea,
                esperado: 'llave foránea a plazas (id_plazas)',
            ),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('plazas-E09: una tabla de plaza opcional también necesita su llave a plazas')]
    public function test_plazas_e09_una_tabla_de_plaza_opcional_tambien_necesita_su_llave_a_plazas(): void
    {
        $this->crear(<<<'SQL'
            create table repartidores (
                id_repartidores bigint generated by default as identity primary key,
                id_plazas bigint,
                created_at timestamptz,
                updated_at timestamptz
            );
        SQL);

        $this->assertEquals([
            new Violacion(
                tabla: 'repartidores',
                columna: 'id_plazas',
                regla: Regla::PlazaForanea,
                esperado: 'llave foránea a plazas (id_plazas)',
            ),
        ], $this->violacionesDePrueba());
    }

    #[TestDox('plazas-E09: una tabla nueva sin id_plazas que no está en la lista no pasa')]
    public function test_plazas_e09_una_tabla_nueva_sin_id_plazas_que_no_esta_en_la_lista_no_pasa(): void
    {
        $this->crear(<<<'SQL'
            create table tabla_nueva (
                id_tabla_nueva bigint generated by default as identity primary key,
                created_at timestamptz,
                updated_at timestamptz
            );
        SQL);

        $this->assertEquals([
            new Violacion(tabla: 'tabla_nueva', columna: null, regla: Regla::Plaza, esperado: 'id_plazas'),
        ], $this->violacionesDePrueba());
    }
}
